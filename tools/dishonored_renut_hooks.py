"""Write the Renut start-up guard for Dishonored (XDK 2.0.21076, default.xex + title update, v0.0.3.17).

The hooked Direct3D functions come from tools/d3d/dishonored_d3d_funcs.toml (matched against ME2 with tools/d3d_match.py,
then each one verified: call order, device fields; the evidence is on every line of that file). For each, the guard
holds an FNV-1a hash of its first 64 bytes in the loaded image; Direct3D_CreateDevice compares them before it hooks
anything, so a different executable is refused instead of drawn wrongly.

  python tools/dishonored_renut_hooks.py [--image out/default_image.bin] [--map tools/d3d/dishonored_d3d_funcs.toml]
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = 0x82000000


def fnv32(data: bytes) -> int:
    value = 2166136261
    for byte in data:
        value = ((value ^ byte) * 16777619) & 0xFFFFFFFF
    return value


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", type=Path, default=ROOT / "out/default_image.bin")
    parser.add_argument("--map", type=Path, default=ROOT / "tools/d3d/dishonored_d3d_funcs.toml")
    args = parser.parse_args()
    image = args.image.read_bytes()
    rows = [(int(a, 16), n) for a, n in re.findall(r'^0x([0-9A-F]{8}) = \{ name = "(\w+)" \}', args.map.read_text(), re.M)]
    if len(rows) != 35:
        raise SystemExit(f"expected 35 functions in {args.map}, found {len(rows)}")
    lines = ["// Generated by tools/dishonored_renut_hooks.py from Dishonored's loaded image "
             "(default.xex + title update, v0.0.3.17).",
             "// The namespace keeps ME2's name: device.cpp reads it there.",
             "#pragma once", "#include <cstdint>", "namespace renut::gpu::me2 {",
             "struct GuestCodeGuard { uint32_t address, bytes, fnv32; const char* name; };",
             "inline constexpr GuestCodeGuard kGuestCodeGuards[] = {"]
    for va, name in sorted(rows):
        code = image[va - BASE:va - BASE + 64]
        lines.append(f'  {{0x{va:08X}u, 64u, 0x{fnv32(code):08X}u, "{name}"}},')
    lines += ["};", "}  // namespace renut::gpu::me2", ""]
    out = ROOT / "app/src/renut_engine/gpu/d3d/me2_hook_map.h"
    out.write_text("\n".join(lines), newline="\n")
    print(f"{out}: {len(rows)} guards")


if __name__ == "__main__":
    main()
